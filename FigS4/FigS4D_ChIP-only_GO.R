message("Genes used in GO BP test: ", length(genes_for_go))
message("Genome-wide TAIR genes: ", length(valid_tair_ids))
message("Genome-wide genes with GO BP annotation: ", length(universe))
message("BH-adjusted significance threshold: ", fdr_cutoff)
message("rrvgo method: Wang")
message("rrvgo similarity threshold: ", rrvgo_threshold)
message("")
message("Saved input gene set: ",
        paste0(out_prefix, "_input_gene_set.csv"))
message("Saved genes used in GO: ",
        paste0(out_prefix, "_genes_used_in_GO.csv"))
message("Saved full TAIR gene universe: ",
        paste0(out_prefix, "_full_TAIR_gene_universe.csv"))
message("Saved effective GO BP background: ",
        paste0(out_prefix, "_GO_BP_background.csv"))
message("Saved gene-count summary: ",
        paste0(out_prefix, "_gene_counts.csv"))
message("Saved full enrichment table: ",
