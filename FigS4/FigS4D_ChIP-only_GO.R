# =============================================================================
# GO Biological Process enrichment of ChIP-only genes
#
# Gene set:
#   HsfA2/HsfA3 ChIP-bound genes outside the three defined Col-0 HSR classes.
#
# Analysis:
#   - Hypergeometric over-representation test
#   - Benjamini-Hochberg correction
#   - Significant GO terms: adjusted p < 0.05
#   - rrvgo reduction using Wang similarity, threshold = 0.7
#   - Dotplot of up to 10 representative GO BP terms
# =============================================================================


# ----------------------------- 0. Packages -----------------------------

suppressPackageStartupMessages({
  library(clusterProfiler)
  library(org.At.tair.db)
  library(rrvgo)
  library(dplyr)
  library(tibble)
  library(ggplot2)
  library(stringr)
})


# ----------------------------- 1. Settings -----------------------------

fdr_cutoff <- 0.05
rrvgo_threshold <- 0.7
max_terms_to_plot <- 10

out_prefix <- "ChIP_only_genes_GO_BP"


# ----------------------------- 2. Helper functions --------------------

clean_gene_id <- function(x) {
  x <- trimws(as.character(x))
  x <- sub(
    "^(gene|transcript|mRNA|rna):",
    "",
    x,
    ignore.case = TRUE
  )
  x <- sub("\\.[0-9]+$", "", x)
  toupper(trimws(x))
}


clean_gene_set <- function(x) {
  x <- clean_gene_id(x)
  unique(x[!is.na(x) & nzchar(x)])
}


write_gene_list <- function(genes, filename) {
  write.csv(
    data.frame(gene = sort(unique(genes))),
    filename,
    row.names = FALSE
  )
}


format_unreduced_terms <- function(terms) {
  if (nrow(terms) == 0L) {
    return(tibble())
  }
  
  terms %>%
    transmute(
      GO_ID = ID,
      Description,
      p.adjust,
      Count,
      GeneRatio,
      n_terms_collapsed = 1L,
      log10FDR = -log10(
        pmax(p.adjust, .Machine$double.xmin)
      )
    )
}


# ----------------------------- 3. Input gene set -----------------------

# Use the ChIP-only gene set generated by the preceding workflow.
if (!exists("q_chip_only", inherits = TRUE)) {
  stop(
    "Object 'q_chip_only' is not available. ",
    "Run the preceding ChIP/HSR workflow first."
  )
}


q_chip_only_raw <- get("q_chip_only", inherits = TRUE)

if (!is.atomic(q_chip_only_raw) || !is.null(dim(q_chip_only_raw))) {
  stop("'q_chip_only' must be a vector of gene identifiers.")
}


chip_only_genes <- clean_gene_set(q_chip_only_raw)


if (length(chip_only_genes) == 0L) {
  stop(
    "'q_chip_only' is empty after gene-ID cleanup. ",
    "Check the upstream ChIP-only gene-set definition."
  )
}


message("Input: existing q_chip_only object")
message("Unique ChIP-only genes: ", length(chip_only_genes))


# ----------------------------- 4. Full Arabidopsis gene universe -------

valid_tair_ids <- unique(
  clean_gene_set(
    AnnotationDbi::keys(
      org.At.tair.db,
      keytype = "TAIR"
    )
  )
)


if (length(valid_tair_ids) == 0L) {
  stop(
    "No TAIR identifiers were retrieved from org.At.tair.db."
  )
}


message(
  "Genome-wide TAIR identifiers in org.At.tair.db: ",
  length(valid_tair_ids)
)


# ----------------------------- 5. Define the effective GO BP background -

# Determine which TAIR IDs have at least one GO Biological Process
# annotation. Genes without a BP annotation cannot contribute to a
# GO BP over-representation test.
go_annotation <- AnnotationDbi::select(
  org.At.tair.db,
  keys = valid_tair_ids,
  keytype = "TAIR",
  columns = c("GO", "ONTOLOGY")
)


bp_annotated_genes <- unique(
  clean_gene_set(
    go_annotation$TAIR[
      !is.na(go_annotation$GO) &
        !is.na(go_annotation$ONTOLOGY) &
        go_annotation$ONTOLOGY == "BP"
    ]
  )
)


universe <- intersect(
  valid_tair_ids,
  bp_annotated_genes
)


if (length(universe) == 0L) {
  stop(
    "No GO BP-annotated TAIR genes were found. ",
    "Check org.At.tair.db and the GO annotation mapping."
  )
}


message(
  "Genome-wide genes with GO BP annotation: ",
  length(universe)
)


# ----------------------------- 6. Prepare the test gene set -------------

chip_only_valid_tair <- intersect(
  chip_only_genes,
  valid_tair_ids
)


genes_for_go <- intersect(
  chip_only_valid_tair,
  universe
)


if (length(genes_for_go) == 0L) {
  stop(
    "No ChIP-only genes with GO BP annotations remain for the test. ",
    "Check the gene IDs and annotation mapping."
  )
}


n_not_valid_tair <- length(
  setdiff(chip_only_genes, valid_tair_ids)
)


n_no_bp_annotation <- length(
  setdiff(chip_only_valid_tair, universe)
)


gene_count_summary <- tibble(
  item = c(
    "Input ChIP-only genes",
    "Input genes matching valid TAIR IDs",
    "Genes used in GO BP test",
    "Input genes not matching valid TAIR IDs",
    "Valid TAIR genes without GO BP annotation",
    "Genome-wide TAIR genes in org.At.tair.db",
    "Genome-wide genes with GO BP annotation"
  ),
  n_genes = c(
    length(chip_only_genes),
    length(chip_only_valid_tair),
    length(genes_for_go),
    n_not_valid_tair,
    n_no_bp_annotation,
    length(valid_tair_ids),
    length(universe)
  )
)


message("")
message("Gene-set and background summary:")
print(gene_count_summary)


# ----------------------------- 7. Save input and background ------------

write_gene_list(
  chip_only_genes,
  paste0(out_prefix, "_input_gene_set.csv")
)


write_gene_list(
  genes_for_go,
  paste0(out_prefix, "_genes_used_in_GO.csv")
)


write_gene_list(
  valid_tair_ids,
  paste0(out_prefix, "_full_TAIR_gene_universe.csv")
)


write_gene_list(
  universe,
  paste0(out_prefix, "_GO_BP_background.csv")
)


write.csv(
  gene_count_summary,
  paste0(out_prefix, "_gene_counts.csv"),
  row.names = FALSE
)


# ----------------------------- 8. GO BP enrichment ---------------------

message("")
message("Running GO Biological Process enrichment...")
message("Background: genome-wide Arabidopsis TAIR genes with GO BP annotation.")


ego <- clusterProfiler::enrichGO(
  gene = genes_for_go,
  universe = universe,
  OrgDb = org.At.tair.db,
  keyType = "TAIR",
  ont = "BP",
  pAdjustMethod = "BH",
  pvalueCutoff = 1,
  qvalueCutoff = 1,
  readable = FALSE
)


all_go_results <- as.data.frame(ego)


all_results_file <- paste0(
  out_prefix,
  "_all_enrichment.csv"
)


write.csv(
  all_go_results,
  all_results_file,
  row.names = FALSE
)


if (nrow(all_go_results) == 0L) {
  
  message(
    "No GO BP terms were returned. ",
    "The enrichment table was saved; no dotplot will be generated."
  )
  
  write.csv(
    tibble(),
    paste0(out_prefix, "_reduced_terms.csv"),
    row.names = FALSE
  )
  
} else {
  
  
  # ----------------------------- 9. FDR filtering ----------------------
  
  sig_go_results <- all_go_results %>%
    filter(
      !is.na(p.adjust),
      p.adjust < fdr_cutoff
    )
  
  
  message(
    "Significant GO BP terms before semantic reduction: ",
    nrow(sig_go_results)
  )
  
  
  if (nrow(sig_go_results) == 0L) {
    
    message(
      "No GO BP terms passed BH-adjusted p < ",
      fdr_cutoff,
      ". The complete enrichment table was saved."
    )
    
    write.csv(
      tibble(),
      paste0(out_prefix, "_reduced_terms.csv"),
      row.names = FALSE
    )
    
  } else {
    
    
    # ------------------------- 10. rrvgo reduction ---------------------
    
    reduce_go_terms <- function(terms) {
      
      terms <- terms %>%
        distinct(ID, .keep_all = TRUE)
      
      
      if (nrow(terms) == 0L) {
        return(tibble())
      }
      
      
      if (nrow(terms) == 1L) {
        return(format_unreduced_terms(terms))
      }
      
      
      sim_matrix <- tryCatch(
        rrvgo::calculateSimMatrix(
          unique(terms$ID),
          orgdb = "org.At.tair.db",
          keytype = "TAIR",
          ont = "BP",
          method = "Wang"
        ),
        error = function(e) {
          message(
            "rrvgo similarity calculation failed; keeping all ",
            "significant terms. Error: ",
            conditionMessage(e)
          )
          NULL
        }
      )
      
      
      if (
        is.null(sim_matrix) ||
        nrow(sim_matrix) == 0L
      ) {
        return(format_unreduced_terms(terms))
      }
      
      
      terms_with_similarity <- terms %>%
        filter(ID %in% rownames(sim_matrix))
      
      
      terms_without_similarity <- terms %>%
        filter(!ID %in% rownames(sim_matrix))
      
      
      if (nrow(terms_with_similarity) == 0L) {
        return(format_unreduced_terms(terms))
      }
      
      
      if (nrow(terms_with_similarity) == 1L) {
        return(
          bind_rows(
            format_unreduced_terms(terms_with_similarity),
            format_unreduced_terms(terms_without_similarity)
          )
        )
      }
      
      
      sim_matrix <- sim_matrix[
        terms_with_similarity$ID,
        terms_with_similarity$ID,
        drop = FALSE
      ]
      
      
      scores <- setNames(
        -log10(
          pmax(
            terms_with_similarity$p.adjust,
            .Machine$double.xmin
          )
        ),
        terms_with_similarity$ID
      )
      
      
      reduced <- tryCatch(
        rrvgo::reduceSimMatrix(
          sim_matrix,
          scores = scores,
          threshold = rrvgo_threshold,
          orgdb = "org.At.tair.db"
        ) %>%
          as.data.frame(),
        error = function(e) {
          message(
            "rrvgo reduction failed; keeping all significant terms. Error: ",
            conditionMessage(e)
          )
          NULL
        }
      )
      
      
      if (
        is.null(reduced) ||
        nrow(reduced) == 0L ||
        !all(c("go", "parent") %in% names(reduced))
      ) {
        return(format_unreduced_terms(terms))
      }
      
      
      collapsed_counts <- reduced %>%
        group_by(parent) %>%
        summarise(
          n_terms_collapsed = n_distinct(go),
          .groups = "drop"
        )
      
      
      representatives <- reduced %>%
        filter(go == parent) %>%
        distinct(parent, .keep_all = TRUE) %>%
        dplyr::select(parent)
      
      
      representative_terms <- representatives %>%
        left_join(
          collapsed_counts,
          by = "parent"
        ) %>%
        left_join(
          terms_with_similarity,
          by = c("parent" = "ID")
        ) %>%
        transmute(
          GO_ID = parent,
          Description,
          p.adjust,
          Count,
          GeneRatio,
          n_terms_collapsed = as.integer(n_terms_collapsed),
          log10FDR = -log10(
            pmax(
              p.adjust,
              .Machine$double.xmin
            )
          )
        )
      
      
      # Preserve significant GO terms that were not represented in
      # the semantic-similarity matrix.
      bind_rows(
        representative_terms,
        format_unreduced_terms(terms_without_similarity)
      ) %>%
        distinct(GO_ID, .keep_all = TRUE)
    }
    
    
    reduced_go <- reduce_go_terms(
      sig_go_results
    )
    
    
    reduced_file <- paste0(
      out_prefix,
      "_reduced_terms.csv"
    )
    
    
    write.csv(
      reduced_go,
      reduced_file,
      row.names = FALSE
    )
    
    
    if (nrow(reduced_go) == 0L) {
      
      message(
        "No representative GO BP terms remained after semantic reduction."
      )
      
    } else {
      
      
      # ------------------------- 11. Prepare dotplot -------------------
      
      plot_data <- reduced_go %>%
        filter(
          is.finite(log10FDR),
          !is.na(Description)
        ) %>%
        arrange(desc(log10FDR))
      
      
      if (is.finite(max_terms_to_plot)) {
        plot_data <- plot_data %>%
          slice_head(n = max_terms_to_plot)
      }
      
      
      if (nrow(plot_data) == 0L) {
        
        message("No finite GO BP enrichment values available for plotting.")
        
      } else {
        
        
        plot_data <- plot_data %>%
          mutate(
            TermKey = paste0(
              Description,
              " [GO:",
              GO_ID,
              "]"
            )
          )
        
        
        plot_data$TermKey <- factor(
          plot_data$TermKey,
          levels = rev(unique(plot_data$TermKey))
        )
        
        
        p_go <- ggplot(
          plot_data,
          aes(
            x = log10FDR,
            y = TermKey
          )
        ) +
          geom_point(
            aes(
              size = Count,
              colour = log10FDR
            ),
            alpha = 0.95
          ) +
          scale_colour_gradient(
            low = "#3B0066",
            high = "#E60026",
            name = expression(-log[10](FDR))
          ) +
          scale_size_continuous(
            range = c(2.5, 8),
            breaks = pretty(plot_data$Count, n = 4),
            name = "Gene count"
          ) +
          scale_x_continuous(
            expand = expansion(mult = c(0.02, 0.08))
          ) +
          scale_y_discrete(
            labels = function(x) {
              stringr::str_wrap(
                sub(" \\[GO:.*$", "", x),
                width = 40
              )
            }
          ) +
          labs(
            title = "GO BP enrichment of ChIP-only genes",
            subtitle = paste0(
              "Genome-wide Arabidopsis GO BP background; BH-adjusted p < ",
              fdr_cutoff
            ),
            x = expression(-log[10](FDR) ~ "of representative term"),
            y = NULL
          ) +
          theme_bw(base_size = 11) +
          theme(
            plot.title = element_text(
              size = 14,
              hjust = 0,
              face = "bold"
            ),
            plot.subtitle = element_blank(),
            panel.grid.minor = element_blank(),
            panel.grid.major = element_line(
              colour = "grey88",
              linewidth = 0.3
            ),
            axis.text.y = element_text(
              size = 13,
              colour = "black"
            ),
            axis.text.x = element_text(
              colour = "black",
              size = 13
            ),
            axis.title.x = element_text(size = 15),
            legend.position = "bottom",
            legend.box = "vertical",
            legend.title = element_text(size = 10),
            legend.text = element_text(size = 9),
            plot.margin = margin(8, 10, 8, 8)
          )
        
        
        print(p_go)
        
        
        # --------------------- 12. Save dotplot ------------------------
        
        png_file <- paste0(
          out_prefix,
          "_dotplot.png"
        )
        
        pdf_file <- paste0(
          out_prefix,
          "_dotplot.pdf"
        )
        
        
        plot_height <- max(
          5.0,
          2.0 + 0.42 * nrow(plot_data)
        )
        
        
        ggsave(
          filename = png_file,
          plot = p_go,
          width = 7.0,
          height = plot_height,
          units = "in",
          dpi = 300,
          bg = "white"
        )
        
        
        ggsave(
          filename = pdf_file,
          plot = p_go,
          width = 8.2,
          height = plot_height,
          units = "in",
          bg = "white"
        )
        
        
        message("Saved reduced GO BP table: ", reduced_file)
        message("Saved PNG dotplot: ", png_file)
        message("Saved PDF dotplot: ", pdf_file)
      }
    }
  }
}


